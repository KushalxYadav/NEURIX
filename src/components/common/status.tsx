import { AlertTriangle, CheckCircle2, CircleDashed, CircleSlash, Loader2, ShieldCheck, Sparkles, XCircle } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import type { Evidence, FileStatus } from "@/modules/sources/types";

const STATUS: Record<FileStatus, { label: string; tone: "success" | "warning" | "danger" | "neutral" | "info"; Icon: typeof CheckCircle2 }> = {
  completed: { label: "Processed", tone: "success", Icon: CheckCircle2 },
  partially_processed: { label: "Partially processed", tone: "warning", Icon: AlertTriangle },
  failed: { label: "Failed", tone: "danger", Icon: XCircle },
  pending: { label: "Pending", tone: "neutral", Icon: CircleDashed },
  processing: { label: "Processing", tone: "info", Icon: Loader2 },
  skipped: { label: "Skipped", tone: "neutral", Icon: CircleSlash },
  rejected: { label: "Rejected (unsafe)", tone: "danger", Icon: XCircle },
  not_applicable: { label: "Not a study document", tone: "neutral", Icon: CircleSlash },
};

export function StatusBadge({ status }: { status: FileStatus }) {
  const config = STATUS[status] ?? STATUS.pending;
  const Icon = config.Icon;
  return (
    <Badge tone={config.tone}>
      <Icon aria-hidden />
      {config.label}
    </Badge>
  );
}

/**
 * Evidence level of any statement or association shown to the student.
 * Source-confirmed facts come from the uploaded material; unverified ones
 * were inferred and need human confirmation; AI supplementary content is
 * clearly marked as not coming from the teacher's material.
 */
export function EvidenceBadge({ evidence }: { evidence: Evidence | "ai_supplementary" }) {
  if (evidence === "source_confirmed") {
    return (
      <Badge tone="success" title="Directly supported by your uploaded material">
        <ShieldCheck aria-hidden />
        Source confirmed
      </Badge>
    );
  }
  if (evidence === "ai_supplementary") {
    return (
      <Badge tone="violet" title="Additional explanation generated by AI, not from your material">
        <Sparkles aria-hidden />
        AI supplementary
      </Badge>
    );
  }
  return (
    <Badge tone="warning" title="Inferred automatically — needs your verification">
      <AlertTriangle aria-hidden />
      Unverified
    </Badge>
  );
}
